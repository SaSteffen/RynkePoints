#!/usr/bin/env node
// Builds the quote monkeys the Team page shows next to its quote (the monkey
// who says it in a speech bubble, above the team total), like pnpm badge-build
// does for the badges:
//
//   pnpm quote-build
//
// 1. Checks art/quotes/monkeys.json; exits 2 on a problem, or on an original
//    without a monkey, before writing anything.
// 2. Snaps each original in art/quotes/originals/ to the coin palette, in
//    place, as <id>.png (a fraction of the generator's file size).
// 3. Traces it into public/quotes/<id>.svg, the full canvas, 100 units wide,
//    like pnpm illustrations, and removes SVGs whose original is gone.
// 4. Writes src/http/quote-monkeys.ts: every monkey with a finished SVG, which
//    the page picks from; without any it shows the rider-state illustration.
// 5. Updates src/http/art-versions.ts (pnpm art-versions).
//
// Needs ImageMagick and potrace, like pnpm illustrations. Running it again
// without changes changes no file.

import {
	mkdirSync,
	readdirSync,
	readFileSync,
	renameSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { basename, extname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateMonkeys } from "./quote-prompts.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const ART = join(ROOT, "art/quotes");
const ORIGINALS = join(ART, "originals");
const OUT = join(ROOT, "public/quotes");
const LIST = join(ROOT, "src/http/quote-monkeys.ts");

const fail = (lines) => {
	console.error(lines.join("\n"));
	process.exit(2);
};

// 1. Inputs.
const data = JSON.parse(readFileSync(join(ART, "monkeys.json"), "utf8"));
const problems = validateMonkeys(data);
if (!readFileSync(join(ART, "prompt.txt"), "utf8").includes("{{scene}}"))
	problems.push("prompt.txt: no {{scene}}");
if (problems.length > 0)
	fail(["art/quotes is not valid:", ...problems.map((p) => `  ${p}`)]);
const monkeys = new Map(data.monkeys.map((m) => [m.id, m]));

const originals = new Map();
for (const f of readdirSync(ORIGINALS)) {
	if (f.startsWith(".")) continue;
	const id = basename(f, extname(f));
	if (!monkeys.has(id))
		fail([`art/quotes/originals/${f}: no monkey ${id} in monkeys.json`]);
	if (originals.has(id))
		fail([`art/quotes/originals: two originals for ${id}, keep one`]);
	originals.set(id, f);
}

/** Writes only when the content changed, so a rebuild leaves git clean. */
function write(path, content) {
	try {
		if (readFileSync(path, "utf8") === content) return false;
	} catch {}
	writeFileSync(path, content);
	return true;
}

// 2. and 3. Snap and trace.
mkdirSync(OUT, { recursive: true });
if (originals.size > 0) {
	// Loaded only when there is something to trace: it needs ImageMagick.
	const { snapToPalette, traceImage } = await import("./trace.mjs");
	for (const id of [...originals.keys()].sort()) {
		const file = originals.get(id);
		const png = join(ORIGINALS, `${id}.png`);
		const tmp = join(ORIGINALS, `.${id}.snapping.png`);
		snapToPalette(join(ORIGINALS, file), tmp);
		const same = (() => {
			try {
				return readFileSync(tmp).equals(readFileSync(png));
			} catch {
				return false;
			}
		})();
		if (same) rmSync(tmp);
		else renameSync(tmp, png);
		if (file !== `${id}.png`) rmSync(join(ORIGINALS, file));

		const { height, markup } = traceImage(png);
		const svg =
			`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 ${height}">` +
			`<title>${id}</title>` +
			`<!-- Generated by scripts/quote-build.mjs from art/quotes/originals/${id}.png; replace that, then run pnpm quote-build. -->` +
			`${markup}</svg>\n`;
		const out = join(OUT, `${id}.svg`);
		const changed = write(out, svg);
		const kb = `${Math.round(statSync(out).size / 100) / 10} KB`;
		console.log(`${id}: ${changed ? "written" : "unchanged"}, ${kb}`);
	}
}
for (const f of readdirSync(OUT)) {
	const id = basename(f, ".svg");
	if (!f.endsWith(".svg") || originals.has(id)) continue;
	rmSync(join(OUT, f));
	console.log(`${id}: removed (no original)`);
}

// 4. The list the page reads, in monkeys.json's order.
const ids = data.monkeys.map((m) => m.id).filter((id) => originals.has(id));
write(
	LIST,
	`// Generated by scripts/quote-build.mjs (pnpm quote-build); don't edit.
// The quote monkeys with a finished picture in public/quotes/<id>.svg; the
// Team page's quote picks one of them, else the rider-state illustration.
export const QUOTE_MONKEYS: readonly string[] = [${ids.map((id) => `\n\t"${id}",`).join("")}${ids.length > 0 ? "\n" : ""}];
`,
);
console.log(
	`${ids.length} of ${monkeys.size} quote monkeys have a picture (src/http/quote-monkeys.ts).`,
);

// The pictures' hashes for their addresses.
await import("./art-versions.mjs");
