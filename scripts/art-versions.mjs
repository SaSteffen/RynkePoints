#!/usr/bin/env node
// Writes src/http/art-versions.ts: a short hash of every badge, coin,
// illustration and quote monkey SVG in public/, which the app puts into the picture's address
// as `?v=<hash>` (a follow-up to issue #182). A changed picture gets a new
// address, so public/_headers can let the browser keep each one for good.
// pnpm badge-build, pnpm coin-art, pnpm illustrations and pnpm quote-build run
// it at their end.
// With `--check` nothing is written, and the exit code is 1 when the list
// differs from the files (`pnpm lint` runs it so).
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const OUT = fileURLToPath(new URL("src/http/art-versions.ts", ROOT));
const FOLDERS = ["badges", "coin", "illustrations", "quotes"];

/** A folder's file names; none for a folder that isn't there (yet). */
function names(folder) {
	try {
		return readdirSync(new URL(`public/${folder}/`, ROOT));
	} catch {
		return [];
	}
}

const entries = FOLDERS.flatMap((folder) =>
	names(folder)
		.filter((name) => name.endsWith(".svg"))
		.sort()
		.map((name) => {
			const hash = createHash("sha256")
				.update(readFileSync(new URL(`public/${folder}/${name}`, ROOT)))
				.digest("hex")
				.slice(0, 10);
			return `\n\t"/${folder}/${name}": "${hash}",`;
		}),
);

const content = `// Generated by scripts/art-versions.mjs; don't edit. Each picture's hash,
// for its address (a follow-up to issue #182).
export const ART_VERSIONS: Readonly<Record<string, string>> = {${entries.join("")}
};
`;

let current = "";
try {
	current = readFileSync(OUT, "utf8");
} catch {
	// Not written yet.
}
if (current !== content) {
	if (process.argv.includes("--check")) {
		console.error(
			"src/http/art-versions.ts is out of date; run node scripts/art-versions.mjs",
		);
		process.exit(1);
	}
	writeFileSync(OUT, content);
	console.log(`src/http/art-versions.ts (${entries.length} pictures)`);
}
