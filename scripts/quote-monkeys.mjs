// The Team page's quote monkeys (art/quotes/README.md), built by
// pnpm badge-build after the badges, the same way:
//
// - checks art/quotes/monkeys.json; a problem, or an original without a
//   monkey, stops the run before anything is written;
// - snaps each original in art/quotes/originals/ to the coin palette, in
//   place, as <id>.png;
// - traces it into public/quotes/<id>.svg, the full canvas, 100 units wide,
//   dropping the enclosed background its `holes` point at and the stray
//   doodles inside its `erase` boxes,
//   like pnpm illustrations; a full run skips monkeys whose SVG is committed
//   and unchanged and removes SVGs whose original is gone;
// - writes src/http/quote-monkeys.ts: every monkey with a finished SVG, which
//   the page picks from; without any it shows the rider-state illustration.

import {
	mkdirSync,
	readdirSync,
	readFileSync,
	renameSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { basename, extname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateMonkeys } from "./quote-prompts.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
const ART = join(ROOT, "art/quotes");
const ORIGINALS = join(ART, "originals");
const OUT = join(ROOT, "public/quotes");
const LIST = join(ROOT, "src/http/quote-monkeys.ts");

/** Writes only when the content changed, so a rebuild leaves git clean. */
function write(path, content) {
	try {
		if (readFileSync(path, "utf8") === content) return false;
	} catch {}
	writeFileSync(path, content);
	return true;
}

/**
 * The checked monkey list and the originals by id, or the problems that
 * stop the run.
 */
export function loadMonkeys() {
	const data = JSON.parse(readFileSync(join(ART, "monkeys.json"), "utf8"));
	const problems = validateMonkeys(data).map((p) => `art/quotes: ${p}`);
	if (!readFileSync(join(ART, "prompt.txt"), "utf8").includes("{{scene}}"))
		problems.push("art/quotes/prompt.txt: no {{scene}}");
	const ids = new Set((data.monkeys ?? []).map((m) => m.id));
	const holes = new Map((data.monkeys ?? []).map((m) => [m.id, m.holes ?? []]));
	const erase = new Map((data.monkeys ?? []).map((m) => [m.id, m.erase ?? []]));
	const originals = new Map();
	for (const f of readdirSync(ORIGINALS)) {
		if (f.startsWith(".")) continue;
		const id = basename(f, extname(f));
		if (!ids.has(id))
			problems.push(
				`art/quotes/originals/${f}: no monkey ${id} in monkeys.json`,
			);
		else if (originals.has(id))
			problems.push(`art/quotes/originals: two originals for ${id}, keep one`);
		else originals.set(id, f);
	}
	return { order: [...ids], ids, originals, holes, erase, problems };
}

/**
 * Snaps, traces and lists the monkeys. `only`: the monkeys named on the
 * command line (built even when committed); `filtered`: ids were named at
 * all, so nothing is removed; `committed`: monkey ids whose SVG is committed
 * and unchanged, skipped unless named.
 */
export async function buildQuoteMonkeys(
	{ order, originals, holes, erase },
	{ only, filtered, committed },
) {
	mkdirSync(OUT, { recursive: true });
	const chosen = filtered ? only : [...originals.keys()].sort();
	const todo = chosen.filter((id) => {
		if (!originals.has(id)) {
			console.log(`${id}: no original yet, skipped`);
			return false;
		}
		if (!filtered && committed.has(id)) {
			console.log(
				`${id}: committed, skipped (pnpm badge-build ${id} to rebuild)`,
			);
			return false;
		}
		return true;
	});
	if (todo.length > 0) {
		// Loaded only when there is something to trace: it needs ImageMagick.
		const { snapToPalette, traceImage } = await import("./trace.mjs");
		for (const id of todo) {
			const file = originals.get(id);
			const png = join(ORIGINALS, `${id}.png`);
			const tmp = join(ORIGINALS, `.${id}.snapping.png`);
			snapToPalette(join(ORIGINALS, file), tmp);
			const same = (() => {
				try {
					return readFileSync(tmp).equals(readFileSync(png));
				} catch {
					return false;
				}
			})();
			if (same) rmSync(tmp);
			else renameSync(tmp, png);
			if (file !== `${id}.png`) rmSync(join(ORIGINALS, file));
			originals.set(id, `${id}.png`);

			const { height, markup } = traceImage(png, {
				holes: holes.get(id) ?? [],
				erase: erase.get(id) ?? [],
			});
			const svg =
				`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 ${height}">` +
				`<title>${id}</title>` +
				`<!-- Generated by scripts/badge-build.mjs from art/quotes/originals/${id}.png; replace that, then run pnpm badge-build ${id}. -->` +
				`${markup}</svg>\n`;
			const out = join(OUT, `${id}.svg`);
			const changed = write(out, svg);
			const kb = `${Math.round(statSync(out).size / 100) / 10} KB`;
			console.log(`${id}: ${changed ? "written" : "unchanged"}, ${kb}`);
		}
	}
	if (!filtered) {
		for (const f of readdirSync(OUT)) {
			const id = basename(f, ".svg");
			if (!f.endsWith(".svg") || originals.has(id)) continue;
			rmSync(join(OUT, f));
			console.log(`${id}: removed (no original)`);
		}
	}

	// The list the page reads, in monkeys.json's order.
	const built = new Set(
		readdirSync(OUT)
			.filter((f) => f.endsWith(".svg"))
			.map((f) => basename(f, ".svg")),
	);
	const ids = order.filter((id) => built.has(id));
	write(
		LIST,
		`// Generated by scripts/badge-build.mjs (pnpm badge-build); don't edit.
// The quote monkeys with a finished picture in public/quotes/<id>.svg; the
// Team page's quote picks one of them, else the rider-state illustration.
export const QUOTE_MONKEYS: readonly string[] = [${ids.map((id) => `\n\t"${id}",`).join("")}${ids.length > 0 ? "\n" : ""}];
`,
	);
	console.log(
		`${ids.length} of ${order.length} quote monkeys have a picture (src/http/quote-monkeys.ts).`,
	);
}
