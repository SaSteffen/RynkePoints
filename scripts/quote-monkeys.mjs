// The Team page's quote monkeys (art/quotes/README.md) and Rynke in the fun
// themes' page-switch shows (art/shows/README.md, feature 022), built by
// pnpm badge-build after the badges, the same way:
//
// - checks the set's list (art/quotes/monkeys.json, art/shows/shows.json); a
//   problem, or an original without a picture in the list, stops the run
//   before anything is written;
// - snaps each original in <art>/originals/ to the set's palette (the coin's;
//   the unicorn adds the rainbow), in place, as <id>.png;
// - traces it into public/<out>/<id>.svg, the full canvas, 100 units wide,
//   dropping the enclosed background its `holes` point at and the stray
//   doodles inside its `erase` boxes,
//   like pnpm illustrations; a full run skips pictures whose SVG is committed
//   and unchanged and removes SVGs whose original is gone;
// - writes the set's list for the app (src/http/quote-monkeys.ts,
//   src/http/show-pictures.ts): every picture with a finished SVG, in the
//   list's order.

import {
	mkdirSync,
	readdirSync,
	readFileSync,
	renameSync,
	rmSync,
	statSync,
	writeFileSync,
} from "node:fs";
import { basename, extname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { validateMonkeys, validateShows } from "./quote-prompts.mjs";

const ROOT = fileURLToPath(new URL("../", import.meta.url));

// The coin palette of trace.mjs plus the rainbow (contracts/fun-decorations.md),
// below the ink, for the unicorn's mane and tail (FR-048).
const RAINBOW = [
	"#ff4566",
	"#ff7a2e",
	"#ffb31a",
	"#ffe61a",
	"#a6f21f",
	"#2bea7c",
	"#14e6cf",
	"#1fd0ff",
	"#3fa9ff",
	"#8a7dff",
	"#c45cff",
	"#ff4fb4",
];

/** The two sets built here: where they live and what the app reads. */
const MONKEYS = {
	art: "art/quotes",
	out: "public/quotes",
	list: "monkeys.json",
	key: "monkeys",
	check: validateMonkeys,
	noun: "quote monkeys",
	palette: () => undefined,
	ts: "src/http/quote-monkeys.ts",
	source: (
		ids,
	) => `// Generated by scripts/badge-build.mjs (pnpm badge-build); don't edit.
// The quote monkeys with a finished picture in public/quotes/<id>.svg; the
// Team page's quote picks one of them, else the rider-state illustration.
export const QUOTE_MONKEYS: readonly string[] = [${ids.map((id) => `\n\t"${id}",`).join("")}${ids.length > 0 ? "\n" : ""}];
`,
};

const SHOWS = {
	art: "art/shows",
	out: "public/shows",
	list: "shows.json",
	key: "shows",
	check: validateShows,
	noun: "show pictures",
	palette: async (id) => {
		if (id !== "unicorn") return undefined;
		const { PALETTE, palette } = await import("./trace.mjs");
		const ink = PALETTE.at(-1);
		return palette([
			...PALETTE.slice(0, -1),
			...RAINBOW.map((hex, i) => ({ name: `rainbow-${i + 1}`, hex })),
			ink,
		]);
	},
	ts: "src/http/show-pictures.ts",
	source: (
		ids,
	) => `// Generated by scripts/badge-build.mjs; don't edit. The Rynke pictures of the
// page-switch shows that are built, in art/shows/shows.json's order (feature
// 022 contracts/show-pictures.md, FR-049).
export const SHOW_PICTURES: readonly ("unicorn" | "disco")[] = [${ids.map((id) => `\n\t"${id}",`).join("")}${ids.length > 0 ? "\n" : ""}];
`,
};

/** Writes only when the content changed, so a rebuild leaves git clean. */
function write(path, content) {
	try {
		if (readFileSync(path, "utf8") === content) return false;
	} catch {}
	writeFileSync(path, content);
	return true;
}

/**
 * A set's checked list and its originals by id, or the problems that stop
 * the run.
 */
function loadPictures(set) {
	const art = join(ROOT, set.art);
	const originalsDir = join(art, "originals");
	const data = JSON.parse(readFileSync(join(art, set.list), "utf8"));
	const problems = set.check(data).map((p) => `${set.art}: ${p}`);
	if (!readFileSync(join(art, "prompt.txt"), "utf8").includes("{{scene}}"))
		problems.push(`${set.art}/prompt.txt: no {{scene}}`);
	const items = data[set.key] ?? [];
	const ids = new Set(items.map((m) => m.id));
	const holes = new Map(items.map((m) => [m.id, m.holes ?? []]));
	const erase = new Map(items.map((m) => [m.id, m.erase ?? []]));
	const originals = new Map();
	for (const f of readdirSync(originalsDir)) {
		if (f.startsWith(".")) continue;
		const id = basename(f, extname(f));
		if (!ids.has(id))
			problems.push(
				`${set.art}/originals/${f}: no ${set.key.replace(/s$/, "")} ${id} in ${set.list}`,
			);
		else if (originals.has(id))
			problems.push(`${set.art}/originals: two originals for ${id}, keep one`);
		else originals.set(id, f);
	}
	return { set, order: [...ids], ids, originals, holes, erase, problems };
}

export const loadMonkeys = () => loadPictures(MONKEYS);
export const loadShows = () => loadPictures(SHOWS);

/**
 * Snaps, traces and lists a set's pictures. `only`: the pictures named on the
 * command line (built even when committed); `filtered`: ids were named at
 * all, so nothing is removed; `committed`: ids whose SVG is committed and
 * unchanged, skipped unless named.
 */
export async function buildPictures(
	{ set, order, originals, holes, erase },
	{ only, filtered, committed },
) {
	const originalsDir = join(ROOT, set.art, "originals");
	const out = join(ROOT, set.out);
	mkdirSync(out, { recursive: true });
	const chosen = filtered ? only : [...originals.keys()].sort();
	const todo = chosen.filter((id) => {
		if (!originals.has(id)) {
			console.log(`${id}: no original yet, skipped`);
			return false;
		}
		if (!filtered && committed.has(id)) {
			console.log(
				`${id}: committed, skipped (pnpm badge-build ${id} to rebuild)`,
			);
			return false;
		}
		return true;
	});
	if (todo.length > 0) {
		// Loaded only when there is something to trace: it needs ImageMagick.
		const { snapToPalette, traceImage } = await import("./trace.mjs");
		for (const id of todo) {
			const colours = await set.palette(id);
			const file = originals.get(id);
			const png = join(originalsDir, `${id}.png`);
			const tmp = join(originalsDir, `.${id}.snapping.png`);
			snapToPalette(join(originalsDir, file), tmp, colours);
			const same = (() => {
				try {
					return readFileSync(tmp).equals(readFileSync(png));
				} catch {
					return false;
				}
			})();
			if (same) rmSync(tmp);
			else renameSync(tmp, png);
			if (file !== `${id}.png`) rmSync(join(originalsDir, file));
			originals.set(id, `${id}.png`);

			const { height, markup } = traceImage(png, {
				colours,
				holes: holes.get(id) ?? [],
				erase: erase.get(id) ?? [],
			});
			const svg =
				`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 ${height}">` +
				`<title>${id}</title>` +
				`<!-- Generated by scripts/badge-build.mjs from ${set.art}/originals/${id}.png; replace that, then run pnpm badge-build ${id}. -->` +
				`${markup}</svg>\n`;
			const target = join(out, `${id}.svg`);
			const changed = write(target, svg);
			const kb = `${Math.round(statSync(target).size / 100) / 10} KB`;
			console.log(`${id}: ${changed ? "written" : "unchanged"}, ${kb}`);
		}
	}
	if (!filtered) {
		for (const f of readdirSync(out)) {
			const id = basename(f, ".svg");
			if (!f.endsWith(".svg") || originals.has(id)) continue;
			rmSync(join(out, f));
			console.log(`${id}: removed (no original)`);
		}
	}

	// The list the page reads, in the set's order.
	const built = new Set(
		readdirSync(out)
			.filter((f) => f.endsWith(".svg"))
			.map((f) => basename(f, ".svg")),
	);
	const ids = order.filter((id) => built.has(id));
	write(join(ROOT, set.ts), set.source(ids));
	console.log(
		`${ids.length} of ${order.length} ${set.noun} have a picture (${set.ts}).`,
	);
}
